use crate::source::Span;
use std::fmt;

#[derive(Debug, Clone, PartialEq)]
pub enum FPart {
    Lit(String),
    Expr { lo: usize, hi: usize, spec: Option<String> },
}

#[derive(Debug, Clone, PartialEq)]
pub enum Tok {
    Int(i64),
    Float(f64),
    Str(String),
    FStr(Vec<FPart>),
    Ident(String),

    Show,
    If,
    Otherwise,
    Repeat,
    For,
    In,
    While,
    Function,
    Task,
    Return,
    True,
    False,
    None,
    And,
    Or,
    Not,
    Use,
    Python,
    As,
    Class,
    Try,
    Catch,
    Break,
    Continue,
    Pass,
    Together,
    Await,

    Plus,
    Minus,
    Star,
    Slash,
    SlashSlash,
    Percent,
    StarStar,
    At,
    Assign,
    PlusAssign,
    MinusAssign,
    StarAssign,
    SlashAssign,
    EqEq,
    NotEq,
    Lt,
    Le,
    Gt,
    Ge,
    Arrow,
    FatArrow,
    LParen,
    RParen,
    LBracket,
    RBracket,
    LBrace,
    RBrace,
    Comma,
    Colon,
    Dot,
    Pipe,

    Newline,
    Indent,
    Dedent,
    Eof,
}

impl Tok {
    pub fn keyword(word: &str) -> Option<Tok> {
        Some(match word {
            "show" => Tok::Show,
            "if" => Tok::If,
            "otherwise" | "else" => Tok::Otherwise,
            "repeat" => Tok::Repeat,
            "for" => Tok::For,
            "in" => Tok::In,
            "while" => Tok::While,
            "function" => Tok::Function,
            "task" => Tok::Task,
            "return" => Tok::Return,
            "true" => Tok::True,
            "false" => Tok::False,
            "none" => Tok::None,
            "and" => Tok::And,
            "or" => Tok::Or,
            "not" => Tok::Not,
            "use" => Tok::Use,
            "python" => Tok::Python,
            "as" => Tok::As,
            "class" => Tok::Class,
            "try" => Tok::Try,
            "catch" => Tok::Catch,
            "break" => Tok::Break,
            "continue" => Tok::Continue,
            "pass" => Tok::Pass,
            "together" => Tok::Together,
            "await" => Tok::Await,
            _ => return None,
        })
    }
}

impl fmt::Display for Tok {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let s = match self {
            Tok::Int(n) => return write!(f, "number `{n}`"),
            Tok::Float(n) => return write!(f, "number `{n}`"),
            Tok::Str(_) | Tok::FStr(_) => "string",
            Tok::Ident(name) => return write!(f, "`{name}`"),
            Tok::Show => "`show`",
            Tok::If => "`if`",
            Tok::Otherwise => "`otherwise`",
            Tok::Repeat => "`repeat`",
            Tok::For => "`for`",
            Tok::In => "`in`",
            Tok::While => "`while`",
            Tok::Function => "`function`",
            Tok::Task => "`task`",
            Tok::Return => "`return`",
            Tok::True => "`true`",
            Tok::False => "`false`",
            Tok::None => "`none`",
            Tok::And => "`and`",
            Tok::Or => "`or`",
            Tok::Not => "`not`",
            Tok::Use => "`use`",
            Tok::Python => "`python`",
            Tok::As => "`as`",
            Tok::Class => "`class`",
            Tok::Try => "`try`",
            Tok::Catch => "`catch`",
            Tok::Break => "`break`",
            Tok::Continue => "`continue`",
            Tok::Pass => "`pass`",
            Tok::Together => "`together`",
            Tok::Await => "`await`",
            Tok::Plus => "`+`",
            Tok::Minus => "`-`",
            Tok::Star => "`*`",
            Tok::Slash => "`/`",
            Tok::SlashSlash => "`//`",
            Tok::Percent => "`%`",
            Tok::StarStar => "`**`",
            Tok::At => "`@`",
            Tok::Assign => "`=`",
            Tok::PlusAssign => "`+=`",
            Tok::MinusAssign => "`-=`",
            Tok::StarAssign => "`*=`",
            Tok::SlashAssign => "`/=`",
            Tok::EqEq => "`==`",
            Tok::NotEq => "`!=`",
            Tok::Lt => "`<`",
            Tok::Le => "`<=`",
            Tok::Gt => "`>`",
            Tok::Ge => "`>=`",
            Tok::Arrow => "`->`",
            Tok::FatArrow => "`=>`",
            Tok::LParen => "`(`",
            Tok::RParen => "`)`",
            Tok::LBracket => "`[`",
            Tok::RBracket => "`]`",
            Tok::LBrace => "`{`",
            Tok::RBrace => "`}`",
            Tok::Comma => "`,`",
            Tok::Colon => "`:`",
            Tok::Dot => "`.`",
            Tok::Pipe => "`|`",
            Tok::Newline => "end of line",
            Tok::Indent => "indented block",
            Tok::Dedent => "end of block",
            Tok::Eof => "end of file",
        };
        f.write_str(s)
    }
}

#[derive(Debug, Clone)]
pub struct Token {
    pub tok: Tok,
    pub span: Span,
}
